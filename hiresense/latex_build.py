"""Fixed LaTeX template for the student resume: the layout of the user's own resume source.

The app fills this template from the resume data and compiles it with tectonic. Nothing here is generated by a
language model, so the layout stays the same every time.
"""

import shutil
import subprocess
import tempfile
from pathlib import Path

PREAMBLE = r"""\documentclass[letterpaper,10pt]{article}
\usepackage[margin=0.5in]{geometry}
\usepackage{enumitem}
\usepackage{titlesec}
\usepackage{hyperref}
\pagestyle{empty}
\setlength{\parindent}{0pt}
\hypersetup{colorlinks=true, linkcolor=black, urlcolor=black}
\titleformat{\section}{\large\scshape}{}{0em}{}[\vspace{-3pt}\titlerule]
\titlespacing*{\section}{0pt}{4pt}{2pt}
\setlist[itemize,1]{leftmargin=1.2em, itemsep=0pt, topsep=1pt, label=\textbullet}
\setlist[itemize,2]{leftmargin=1.4em, itemsep=0pt, topsep=0pt, label=\textbullet}
\newcommand{\entry}[2]{\noindent\textbf{#1}\hfill #2\par}
\newcommand{\subentry}[2]{\noindent\textit{#1}\hfill\textit{#2}\par}
"""

SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def escape(text) -> str:
    return "".join(SPECIAL.get(ch, ch) for ch in str(text or ""))


def _visible(data: dict, section: str) -> bool:
    return section not in set(data.get("hidden_sections", []))


def _entries(data: dict, section: str) -> list[str]:
    lines = []
    for entry in data.get(section, []):
        lines.append(f"\\entry{{{escape(entry.get('organization') or entry.get('title'))}}}"
                     f"{{{escape(entry.get('dates'))}}}")
        if entry.get("organization") and entry.get("title"):
            detail = entry["title"]
            if entry.get("field_of_study"):
                detail += f" -- {entry['field_of_study']}"
            lines.append(f"\\subentry{{{escape(detail)}}}{{{escape(entry.get('grade'))}}}")
        elif entry.get("title"):
            lines.append(f"\\subentry{{{escape(entry.get('location'))}}}{{}}")
        bullets = [b["text"] for b in entry.get("bullets", []) if b.get("text")]
        if bullets:
            lines.append("\\begin{itemize}")
            lines += [f"  \\item {escape(text)}" for text in bullets]
            lines.append("\\end{itemize}")
        lines.append("\\vspace{1pt}")
    return lines


def _skills(data: dict) -> list[str]:
    groups: dict[str, list[str]] = {}
    for skill in data.get("skills", []):
        if skill.get("name"):
            groups.setdefault(skill.get("category") or "", []).append(skill["name"])
    lines = ["\\begin{itemize}"]
    for category, names in groups.items():
        label = f"\\textbf{{{escape(category)}}}: " if category else ""
        lines.append(f"  \\item {label}{escape(', '.join(names))}")
    lines.append("\\end{itemize}")
    return lines


def _items(data: dict, section: str) -> list[str]:
    items = [item["text"] for item in data.get(section, []) if item.get("text")]
    if not items:
        return []
    return ["\\begin{itemize}"] + [f"  \\item {escape(text)}" for text in items] + ["\\end{itemize}"]


def build_latex(data: dict) -> str:
    personal = data.get("personal", {})
    contact = [escape(personal.get(k)) for k in ("email", "phone", "location") if personal.get(k)]
    contact += [f"\\href{{{link['url']}}}{{{escape(link.get('label') or link['url'])}}}"
                for link in data.get("links", []) if link.get("url")]
    parts = [PREAMBLE, "\\begin{document}", "\\begin{center}",
             f"  {{\\LARGE\\scshape {escape(personal.get('name'))}}}\\\\[4pt]",
             f"  \\small {' | '.join(contact)}" if contact else "",
             "\\end{center}"]

    sections = [
        ("summary", "Summary", lambda: [escape(data.get("summary"))] if data.get("summary") else []),
        ("education", "Education", lambda: _entries(data, "education")),
        ("skills", "Skills", lambda: _skills(data) if data.get("skills") else []),
        ("experience", "Experience", lambda: _entries(data, "experience")),
        ("internships", "Internships", lambda: _entries(data, "internships")),
        ("projects", "Projects", lambda: _entries(data, "projects")),
        ("certifications", "Certifications", lambda: _entries(data, "certifications")),
        ("achievements", "Achievements", lambda: _items(data, "achievements")),
        ("leadership", "Leadership \\& Responsibilities", lambda: _items(data, "leadership")),
        ("interests", "Interests", lambda: _items(data, "interests")),
    ]
    for key, title, body in sections:
        if not _visible(data, key):
            continue
        content = body()
        if content:
            parts.append(f"\\section*{{{escape(title)}}}")
            parts += content
    parts.append("\\end{document}")
    return "\n".join(part for part in parts if part is not None) + "\n"


class LatexUnavailable(RuntimeError):
    """tectonic is not installed or the source did not compile."""


def compile_latex(source: str, timeout: float = 180.0) -> bytes:
    engine = shutil.which("tectonic")
    if not engine:
        raise LatexUnavailable("LaTeX is not installed. Install tectonic (brew install tectonic) to use the template.")
    with tempfile.TemporaryDirectory() as folder:
        tex = Path(folder) / "resume.tex"
        tex.write_text(source, encoding="utf-8")
        try:
            result = subprocess.run([engine, "--keep-logs", "resume.tex"], cwd=folder, capture_output=True,
                                    text=True, timeout=timeout)
        except subprocess.TimeoutExpired as exc:
            raise LatexUnavailable("The LaTeX build took too long.") from exc
        pdf = Path(folder) / "resume.pdf"
        if result.returncode != 0 or not pdf.exists():
            raise LatexUnavailable("The LaTeX build failed: " + (result.stderr or result.stdout)[-400:])
        return pdf.read_bytes()


def build_latex_pdf(data: dict) -> bytes:
    return compile_latex(build_latex(data))
